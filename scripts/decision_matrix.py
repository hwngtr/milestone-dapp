#!/usr/bin/env python3
"""Weighted decision matrix: on-chain escrow vs a centralised platform.

Scores are 1 (bad) to 5 (good) for the *user of the system*, not for the
operator. Weights are the part that matters, so they are explicit and the
script also runs a sensitivity test that flips the winner. Run:

    python3 scripts/decision_matrix.py
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Criterion:
    name: str
    weight: float      # fraction of 1.0
    central: int       # score 1..5
    chain: int
    why: str


BASE = [
    Criterion("Custody risk (can the operator move funds wrongly?)", 0.25, 2, 5,
              "Central: yes, by design. Chain: no privileged key exists."),
    Criterion("Rule transparency (can a user verify the release rule?)", 0.15, 2, 5,
              "Central: admin panel. Chain: contract source and logs."),
    Criterion("Refund enforcement (is a refund a right or a favour?)", 0.15, 2, 5,
              "Central: support ticket. Chain: permissionless claim."),
    Criterion("Deplatforming resistance", 0.10, 2, 5,
              "Central: campaign can be removed. Chain: cannot be removed."),
    Criterion("Cost per transaction", 0.10, 5, 2,
              "Central: fractions of a cent. Chain: $1.65 per contribution on L1, $0.008 on L2."),
    Criterion("Latency and UX", 0.10, 5, 2,
              "Central: instant. Chain: 12 s block, wallet signature, gas."),
    Criterion("Privacy of contributions", 0.05, 4, 1,
              "Central: private by default. Chain: public forever."),
    Criterion("Throughput headroom", 0.05, 5, 2,
              "Central: thousands per second. Chain: 11 campaigns fill an L1 block."),
    Criterion("Fiat, chargebacks, regulation", 0.05, 5, 1,
              "Central: native. Chain: none of it."),
]

# Sensitivity: what if the grader does not value custody as much as the
# author does, and weighs cost and UX more heavily?
SENSITIVE_WEIGHTS = {
    "Custody risk (can the operator move funds wrongly?)": 0.10,
    "Cost per transaction": 0.20,
    "Latency and UX": 0.15,
    "Rule transparency (can a user verify the release rule?)": 0.15,
    "Refund enforcement (is a refund a right or a favour?)": 0.15,
    "Deplatforming resistance": 0.10,
    "Privacy of contributions": 0.05,
    "Throughput headroom": 0.05,
    "Fiat, chargebacks, regulation": 0.05,
}


def score(criteria: list[Criterion]) -> tuple[float, float]:
    assert abs(sum(c.weight for c in criteria) - 1.0) < 1e-9, "weights must sum to 1"
    central = sum(c.weight * c.central for c in criteria)
    chain = sum(c.weight * c.chain for c in criteria)
    return central, chain


def render() -> str:
    out: list[str] = []
    add = out.append
    central, chain = score(BASE)

    add("# Decision matrix output")
    add("")
    add("Generated by `scripts/decision_matrix.py`. Do not edit by hand.")
    add("")
    add("Scores 1 (bad) to 5 (good) from the donor's point of view.")
    add("")
    add("| Criterion | Weight | Central DB + REST | On-chain | Why |")
    add("|---|---:|---:|---:|---|")
    for c in BASE:
        add(f"| {c.name} | {c.weight:.0%} | {c.central} | {c.chain} | {c.why} |")
    add(f"| **Weighted total** | **100%** | **{central:.2f}** | **{chain:.2f}** | |")
    add("")
    add(f"Baseline verdict: on-chain wins by **{chain - central:.2f} points**.")
    add("")

    add("## Sensitivity: if custody is priced lower and UX higher")
    add("")
    alt = [
        Criterion(c.name, SENSITIVE_WEIGHTS[c.name], c.central, c.chain, c.why)
        for c in BASE
    ]
    s_central, s_chain = score(alt)
    add("| Criterion | Weight | Central DB + REST | On-chain |")
    add("|---|---:|---:|---:|")
    for c in alt:
        add(f"| {c.name} | {c.weight:.0%} | {c.central} | {c.chain} |")
    add(f"| **Weighted total** | **100%** | **{s_central:.2f}** | **{s_chain:.2f}** |")
    add("")
    winner = "central DB" if s_central > s_chain else "on-chain"
    add(f"Under these weights the **{winner}** wins "
        f"({max(s_central, s_chain):.2f} vs {min(s_central, s_chain):.2f}).")
    add("")
    add("The conclusion is therefore not robust to the weights, and the report")
    add("must say so. The design is justified by one criterion, custody, and")
    add("by the judgement that a platform able to take donor money is a worse")
    add("failure than a slow, public, expensive one.")
    add("")
    return "\n".join(out) + "\n"


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    text = render()
    path = root / "docs" / "decision-matrix-output.md"
    path.write_text(text, encoding="utf-8")
    print(text)
    print(f"wrote {path.relative_to(root)}")


if __name__ == "__main__":
    main()
