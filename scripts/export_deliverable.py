#!/usr/bin/env python3
"""Concatenate the Week 1–2 documents into one standalone markdown file.

The project folder is the canonical source; this export exists so the package
can be read in one file (and so the Obsidian vault has a single note to open).
Run from the project root:

    python3 scripts/export_deliverable.py
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
import os

DEST = Path(os.environ.get(
    "MILESTONE_EXPORT_DEST",
    "/home/hwngtr/Documents/Hung Obs/MDs by OpenCode/"
    "milestone-escrow-crowdfunding-week1-2-package.md",
))

DOCS = [
    ("Project proposal", "docs/01-proposal.md"),
    ("Blockchain necessity analysis", "docs/02-blockchain-necessity-analysis.md"),
    ("System architecture", "docs/03-architecture.md"),
    ("Security preview", "docs/04-security-preview.md"),
    ("Appendix A · cost model output", "docs/cost-model-output.md"),
    ("Appendix B · decision matrix output", "docs/decision-matrix-output.md"),
]

HEADER = """# Milestone — escrow crowdfunding dApp
## Week 1–2 package: proposal, necessity analysis, architecture, presentation

**Course:** Current Topics in CS — Blockchain, Web3 & Decentralized Systems
**Institution:** Vietnamese-German University
**Author:** Hưng Trần
**Date:** 6 November 2026
**Status:** ready to submit and present

> Canonical source: `Documents/Hung Obs/01_Studies/Current topic/Individual Project/`
> Diagrams: `diagrams/system-architecture.png`, `campaign-lifecycle.png`,
> `tx-lifecycle.png`.
> Every number below is regenerated by `scripts/cost_model.py` and
> `scripts/decision_matrix.py`.

---

## Contents

1. Project proposal
2. Blockchain necessity analysis
3. System architecture
4. Security preview
5. Appendix A — cost model output
6. Appendix B — decision matrix output

---
"""


def strip_title(text: str) -> str:
    """Drop the first H1 so the concatenation has one title hierarchy."""
    lines = text.splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    while lines and not lines[0].strip():
        lines = lines[1:]
    return "\n".join(lines).rstrip() + "\n"


def build() -> str:
    parts = [HEADER]
    for title, rel in DOCS:
        path = ROOT / rel
        body = strip_title(path.read_text(encoding="utf-8"))
        parts.append(f"\n\n---\n\n## {title}\n\n{body}")
    return "".join(parts)


def main() -> None:
    text = build()
    DEST.parent.mkdir(parents=True, exist_ok=True)
    if DEST.exists():
        print(f"WARNING: overwriting existing file {DEST}")
    DEST.write_text(text, encoding="utf-8")
    words = len(text.split())
    print(f"wrote {DEST}")
    print(f"{words:,} words, {len(text):,} characters")


if __name__ == "__main__":
    main()
