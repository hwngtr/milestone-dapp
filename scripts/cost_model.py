#!/usr/bin/env python3
"""Cost model for the Milestone escrow-crowdfunding dApp.

Every cost figure quoted in the proposal, the necessity analysis and the
slides is produced by this script. Change the parameters below and re-run to
regenerate `docs/cost-model-output.md` and `data/cost-model.csv`.

Gas figures are engineering estimates from the storage layout described in
docs/03-architecture.md. They are not measurements. Replace them with
`forge snapshot` output once the contracts exist (Week 4) and keep this file
as the single source of truth for the cost table.

Usage:
    python3 scripts/cost_model.py
"""

from __future__ import annotations

import csv
from dataclasses import dataclass
from pathlib import Path

# --------------------------------------------------------------------------
# Parameters. Edit these, re-run, and the documents follow.
# --------------------------------------------------------------------------
ETH_USD = 3_000.0          # assumed ETH price, USD. Update to spot price.
L1_GAS_GWEI = 10.0         # L1 execution gas price on a normal day.
L2_GAS_GWEI = 0.05         # L2 effective gas price (zkSync Era / Base range).
GWEI = 1e-9                # ETH per gwei

# Fiat baseline: card processing for a small platform.
STRIPE_PCT = 0.029
STRIPE_FIXED_USD = 0.30
STRIPE_PAYOUT_PCT = 0.0025  # account/payout fee, small but real
DB_ROW_COST_USD = 0.00002   # amortised cost of one Postgres row write

# --------------------------------------------------------------------------
# Gas estimates per user-visible action.
# Basis: EIP-2929/2200 cold SLOAD 2,100; SSTORE zero->non-zero 22,100;
# non-zero->non-zero 2,900; LOG ~1,800; base tx 21,000; calldata ~16/byte.
# --------------------------------------------------------------------------
ACTIONS = [
    # name, gas, new storage slots written, note
    ("Create campaign (factory clone + init)", 220_000, 8,
     "6 config slots + clone creation + CampaignCreated event"),
    ("Contribute", 55_000, 1,
     "new donor slot + totalRaised update + Contributed event"),
    ("Vote on milestone (donor, explicit design)", 50_000, 1,
     "per-donor approval slot + approval tally + event"),
    ("Mark milestone delivered", 40_000, 1,
     "evidence hash + status + window start + event"),
    ("Release milestone to creator", 40_000, 1,
     "status update + credit to creator (pull payment)"),
    ("Object to milestone (donor, optimistic design)", 50_000, 1,
     "per-donor objection slot + objection count + event"),
    ("Claim refund after failed campaign", 45_000, 1,
     "refund-claimed flag + ETH transfer; CEI + pull pattern"),
]


@dataclass
class Row:
    action: str
    gas: int
    slots: int
    note: str
    l1_usd: float
    l2_usd: float
    db_usd: float


def eth_cost(gas: int, gwei: float) -> float:
    """Return cost in ETH for `gas` units at `gwei` gas price."""
    return gas * gwei * GWEI


def build_rows() -> list[Row]:
    rows: list[Row] = []
    for name, gas, slots, note in ACTIONS:
        rows.append(
            Row(
                action=name,
                gas=gas,
                slots=slots,
                note=note,
                l1_usd=eth_cost(gas, L1_GAS_GWEI) * ETH_USD,
                l2_usd=eth_cost(gas, L2_GAS_GWEI) * ETH_USD,
                db_usd=DB_ROW_COST_USD,
            )
        )
    return rows


def stripe_fee(amount_usd: float) -> float:
    """Card processing cost for one charge of `amount_usd`."""
    return amount_usd * STRIPE_PCT + STRIPE_FIXED_USD


def money(x: float) -> str:
    """Format USD with enough precision to stay honest at small values."""
    if x >= 1:
        return f"${x:,.2f}"
    if x >= 0.01:
        return f"${x:.3f}"
    return f"${x:.4f}"


def render() -> str:
    rows = build_rows()
    out: list[str] = []
    add = out.append

    add("# Cost model output")
    add("")
    add("Generated by `scripts/cost_model.py`. Do not edit by hand.")
    add("")
    add("## Assumptions")
    add("")
    add(f"- ETH price: **${ETH_USD:,.0f}**")
    add(f"- L1 execution gas price: **{L1_GAS_GWEI} gwei**")
    add(f"- L2 effective gas price: **{L2_GAS_GWEI} gwei**")
    add(f"- Card processing baseline: **{STRIPE_PCT * 100:.1f}% + ${STRIPE_FIXED_USD:.2f}** per charge")
    add(f"- Postgres row write (amortised): **{money(DB_ROW_COST_USD)}**")
    add("")
    add("Gas estimates are engineering estimates from the storage layout, not")
    add("measurements. They are replaced by `forge snapshot` numbers in Week 4.")
    add("")
    add("## Cost per user action")
    add("")
    add("| Action | Gas | L1 (USD) | L2 (USD) | Central DB (USD) | Note |")
    add("|---|---:|---:|---:|---:|---|")
    for r in rows:
        add(
            f"| {r.action} | {r.gas:,} | {money(r.l1_usd)} | {money(r.l2_usd)} "
            f"| {money(r.db_usd)} | {r.note} |"
        )
    add("")

    # A realistic campaign: 1 creator, 40 donors, 3 milestones.
    donors = 40
    milestones = 3
    create = rows[0]
    contribute = rows[1]
    vote = rows[2]
    deliver = rows[3]
    release = rows[4]
    object_ = rows[5]

    # Design A: every donor votes on every milestone (the obvious design).
    a_l1 = create.l1_usd + donors * contribute.l1_usd + milestones * (donors * vote.l1_usd + release.l1_usd)
    a_l2 = create.l2_usd + donors * contribute.l2_usd + milestones * (donors * vote.l2_usd + release.l2_usd)
    a_gas = create.gas + donors * contribute.gas + milestones * (donors * vote.gas + release.gas)

    # Design B: optimistic release. Creator marks delivery, a challenge
    # window opens, and funds release unless a quorum of donors objects.
    # Happy path needs no donor transaction at all.
    b_l1 = create.l1_usd + donors * contribute.l1_usd + milestones * (deliver.l1_usd + release.l1_usd)
    b_l2 = create.l2_usd + donors * contribute.l2_usd + milestones * (deliver.l2_usd + release.l2_usd)
    b_gas = create.gas + donors * contribute.gas + milestones * (deliver.gas + release.gas)

    db_campaign = create.db_usd + donors * contribute.db_usd + milestones * (deliver.db_usd + release.db_usd)

    avg_ticket = 50.0
    raised = donors * avg_ticket
    stripe_total = donors * stripe_fee(avg_ticket) + raised * STRIPE_PAYOUT_PCT
    stripe_pct_of_raised = 100 * stripe_total / raised

    add(f"## One campaign: {donors} donors x ${avg_ticket:.0f}, {milestones} milestones")
    add("")
    add(f"Raised: **${raised:,.0f}**")
    add("")
    add("| Design | L1 total | L1 % of raised | L2 total | L2 % of raised | Gas |")
    add("|---|---:|---:|---:|---:|---:|")
    add(f"| A. Per-donor vote on every milestone | {money(a_l1)} | {100 * a_l1 / raised:.2f}% | {money(a_l2)} | {100 * a_l2 / raised:.3f}% | {a_gas:,} |")
    add(f"| B. Optimistic release + objection window | {money(b_l1)} | {100 * b_l1 / raised:.2f}% | {money(b_l2)} | {100 * b_l2 / raised:.3f}% | {b_gas:,} |")
    add(f"| Central database (no trust guarantee) | {money(db_campaign)} | 0.000% | - | - | - |")
    add(f"| Card processing for the same money | {money(stripe_total)} | {stripe_pct_of_raised:.2f}% | - | - | - |")
    add("")
    add(f"Design A costs **{money(a_l1 - b_l1)} more on L1** for the same campaign.")
    add(f"The naive design spends {100 * (a_l1 - b_l1) / a_l1:.0f}% of the total on")
    add("donors confirming that work they can already see was delivered.")
    add("")
    add("Design B is the one implemented. A donor pays nothing in the happy")
    add("path. The objection path costs one transaction, and it is paid only by")
    add("donors who believe the release is wrong.")
    add("")

    add("### Reading")
    add("")
    add("On L1 the transaction cost is the same order of magnitude as card fees,")
    add("so L1 does not win on price. On an L2 both designs are roughly two")
    add("orders of magnitude cheaper than card processing, which is the only")
    add("economic argument that makes a per-donation on-chain flow defensible.")
    add("This is why the design targets an L2 testnet and measures L1 as the")
    add("comparison baseline.")
    add("")

    # Scale scenario for throughput discussion.
    add("## Throughput sanity check (Design B)")
    add("")
    add("| Quantity | Value |")
    add("|---|---:|")
    add(f"| Transactions per campaign (create + contributions + delivery + release) | {1 + donors + 2 * milestones} |")
    add(f"| L1 gas per campaign | {b_gas:,} |")
    add(f"| Campaigns per L1 block at 30M gas (theoretical, all gas to this app) | {30_000_000 // b_gas or 1} |")
    add(f"| Campaigns per second on L1 (12 s blocks, theoretical maximum) | {(30_000_000 / b_gas) / 12:.2f} |")
    add("")
    per_block = 30_000_000 / b_gas
    add(f"One campaign uses {100 * b_gas / 30_000_000:.1f}% of an L1 block, so at most about")
    add(f"{per_block:.0f} campaigns fit in a block, or {per_block / 12:.2f} per second with")
    add("every block devoted to this application. That ceiling is the strongest")
    add("argument against L1 at scale, and it belongs next to the cost table.")
    add("")

    return "\n".join(out) + "\n"


def write_csv(path: Path) -> None:
    rows = build_rows()
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["action", "gas", "new_storage_slots", "l1_usd", "l2_usd", "central_db_usd", "note"])
        for r in rows:
            writer.writerow([r.action, r.gas, r.slots, f"{r.l1_usd:.6f}", f"{r.l2_usd:.6f}", f"{r.db_usd:.8f}", r.note])


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    text = render()
    out_md = root / "docs" / "cost-model-output.md"
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text(text, encoding="utf-8")
    write_csv(root / "data" / "cost-model.csv")
    print(text)
    print(f"wrote {out_md.relative_to(root)}")


if __name__ == "__main__":
    main()
